export interface BlogAuthor {
  name: string;
  role: string;
  avatar?: string;
}

export type PostStatus = 'draft' | 'published' | 'scheduled';

export interface BlogPost {
  id: string;
  slug: string;
  title: string;
  subtitle?: string;
  excerpt: string;
  content: string; // Rich HTML string generated by TipTap
  coverImage?: string;
  coverCaption?: string;
  category: string;
  tags: string[];
  author: BlogAuthor;
  status: PostStatus;
  publishedAt: string;
  updatedAt: string;
  readingTime: number; // in minutes
  featured?: boolean;
  seoTitle?: string;
  seoDescription?: string;
  seoKeywords?: string;
}

export interface BlogCategory {
  id: string;
  name: string;
  slug: string;
  description?: string;
  color?: string;
}

export interface EditorTemplate {
  id: string;
  name: string;
  description: string;
  icon: string;
  defaultTitle: string;
  defaultExcerpt: string;
  defaultCategory: string;
  content: string;
}
